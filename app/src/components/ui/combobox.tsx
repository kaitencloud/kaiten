/**
 * A combobox whose search box and list render in place, always open, instead of in a popup of
 * their own: for a Popover or a dialog that already provides the surface. Give it `items`, which
 * filtering and the empty state need.
 */
function ComboboxPanel<
  Value,
  Multiple extends boolean | undefined = false,
  Item = Value,
>({
  className,
  children,
  ...props
}: Omit<ComboboxPrimitive.Root.Props<Value, Multiple, Item>, "inline" | "open"> & {
  className?: string
}) {
  return (
    <ComboboxPrimitive.Root
      inline
      open
      // The first item is highlighted as soon as the list shows and while typing, so Enter picks it.
      // Root's types only list `boolean`; the shared implementation honors "always" for a list
      // that is open from the start.
      autoHighlight={"always" as unknown as boolean}
      {...props}
    >
      <div
        data-slot="combobox-panel"
        className={cn(
          "flex h-full w-full flex-col overflow-hidden rounded-md bg-popover text-popover-foreground",
          className
        )}
      >
        {children}
      </div>
    </ComboboxPrimitive.Root>
  )
}

