type IconRef = SVGSVGElement;
type IconProps = Omit<React.HTMLAttributes<IconRef>, 'viewBox'> & {
  ref?: React.Ref<IconRef>;
};

function createIcon({
  displayName,
  viewBox,
  path,
}: {
  displayName: string;
  viewBox: string;
  path: React.ReactNode;
}) {
  function Icon({ className, ref, ...props }: IconProps) {
    return (
      <svg
        ref={ref}
        viewBox={viewBox}
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        className={cn('size-[1em]', className)}
        aria-hidden="true"
        {...props}
      >
        {path}
      </svg>
    );
  }
  Icon.displayName = displayName;

  return Icon;
}

